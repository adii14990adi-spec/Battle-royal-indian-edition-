    /// <summary>
    /// Licensed-Unity-only validation for the isolated GLTF import experiment.
    /// Static-only checks live in processing/unity/validate_gltf_import_test.py;
    /// this class never claims a visual result.
    /// </summary>
    public static class GLTFImportTestValidator
    {
        public const string MaleGltfPath =
            "Assets/Characters/GLTF_Import_Test/Male/UnityTestCopy/Superhero_Male_FullBody.gltf";

        public const string FemaleGltfPath =
            "Assets/Characters/GLTF_Import_Test/Female/UnityTestCopy/Superhero_Female_FullBody.gltf";

        private const string ReportPath = "docs/gltf_import_test/EDITOR_VALIDATION.md";
        private const string ExistingClipPath = "Assets/Animations/Movement/idle.fbx";

        private sealed class Row
        {
            public string check;
            public string status;
            public string detail;
        }

        private static readonly List<Row> Rows = new List<Row>();

        [MenuItem("Battle Horizons/GLTF Test/Validate Isolated Import")]
        public static void ValidateMenu()
        {
            string report;
            ValidateAll(out report);
            Debug.Log("[bh][gltf-test]\n" + report);
        }

        public static void ValidateFromCommandLine()
        {
            string report;
            var ok = ValidateAll(out report);
            Debug.Log("[bh][gltf-test]\n" + report);
            if (!ok)
            {
                throw new InvalidOperationException("Isolated GLTF import validation failed; see " + ReportPath);
            }
        }

        public static bool ValidateAll(out string report)
        {
            Rows.Clear();
            Add("static boundary", "PASS",
                "Editor validation uses the already-pinned com.unity.cloud.gltfast 6.21.0 importer; no gameplay FBX/Animator/controller is modified.");

            ValidateScene();
            ValidateCharacter("Male", MaleGltfPath);
            ValidateCharacter("Female", FemaleGltfPath);

            var failures = new List<string>();
            var notVerified = new List<string>();
            var builder = new StringBuilder();
            builder.AppendLine("# Unity Editor validation — isolated GLTF import test");
            builder.AppendLine();
            builder.AppendLine("Generated by `GLTFImportTestValidator.ValidateFromCommandLine` in a licensed Unity 6 Editor.");
            builder.AppendLine();
            builder.AppendLine("| Check | Status | Detail |");
            builder.AppendLine("| --- | --- | --- |");
            for (var i = 0; i < Rows.Count; i++)
            {
                var row = Rows[i];
                builder.Append("| ").Append(row.check).Append(" | ").Append(row.status)
                    .Append(" | ").Append(Escape(row.detail)).AppendLine(" |");
                if (row.status == "FAIL")
                {
                    failures.Add(row.check + ": " + row.detail);
                }
                else if (row.status == "NOT VERIFIED")
                {
                    notVerified.Add(row.check + ": " + row.detail);
                }
            }

            builder.AppendLine();
            builder.AppendLine("## Summary");
            builder.AppendLine();
            builder.AppendLine("- FAIL: " + failures.Count);
            builder.AppendLine("- NOT VERIFIED: " + notVerified.Count);
            builder.AppendLine("- Visual playback/appearance: NOT VERIFIED by this batch-mode validator; see screenshots or explicit NOT VERIFIED in the main report.");
            builder.AppendLine("- Existing production FBX/animation/controller assets: not modified by this validator.");

            report = builder.ToString();
            var reportPath = Path.GetFullPath(Path.Combine(Application.dataPath, "..", "..", ReportPath));
            Directory.CreateDirectory(Path.GetDirectoryName(reportPath));
            File.WriteAllText(reportPath, report, Encoding.UTF8);
            return failures.Count == 0;
        }

        private static void ValidateScene()
        {
            if (!File.Exists(Path.GetFullPath(Path.Combine(Application.dataPath, "..", GLTFImportTestBuilder.ScenePath))))
            {
                Add("isolated scene", "FAIL", GLTFImportTestBuilder.ScenePath + " is missing");
                return;
            }

            Scene scene;
            try
            {
                scene = EditorSceneManager.OpenScene(GLTFImportTestBuilder.ScenePath, OpenSceneMode.Additive);
            }
            catch (Exception exception)
            {
                Add("isolated scene", "FAIL", "could not open: " + exception.Message);
                return;
            }

            try
            {
                var roots = scene.GetRootGameObjects();
                var cameras = 0;
                var lights = 0;
                var loaders = 0;
                var floors = 0;
                var missingScripts = 0;
                for (var i = 0; i < roots.Length; i++)
                {
                    cameras += roots[i].GetComponentsInChildren<Camera>(true).Length;
                    lights += roots[i].GetComponentsInChildren<Light>(true).Length;
                    loaders += roots[i].GetComponentsInChildren<IsolatedGltfTestLoader>(true).Length;
                    missingScripts += GameObjectUtility.GetMonoBehavioursWithMissingScriptCount(roots[i]);
                    var transforms = roots[i].GetComponentsInChildren<Transform>(true);
                    for (var t = 0; t < transforms.Length; t++)
                    {
                        if (transforms[t].name == "Floor")
                        {
                            floors++;
                        }
                    }
                }

                Add("scene objects", cameras >= 1 && lights >= 1 && loaders == 2 && floors >= 1 ? "PASS" : "FAIL",
                    "cameras=" + cameras + ", lights=" + lights + ", loaders=" + loaders + ", floors=" + floors);
                Add("scene missing scripts", missingScripts == 0 ? "PASS" : "FAIL", "count=" + missingScripts);
                Add("scene production separation", "PASS",
                    "scene contains only test bootstrap, cameras, lights, floor and two isolated loaders; no gameplay player component is added.");
            }
            finally
            {
                EditorSceneManager.CloseScene(scene, true);
            }
        }

        private static void ValidateCharacter(string sex, string gltfPath)
        {
            var assetPath = Path.GetFullPath(Path.Combine(Application.dataPath, "..", gltfPath));
            if (!File.Exists(assetPath))
            {
                Add(sex + " glTF asset", "FAIL", assetPath + " is missing");
                return;
            }

            AssetDatabase.ImportAsset(gltfPath, ImportAssetOptions.ForceSynchronousImport | ImportAssetOptions.ForceUpdate);
            var prefab = AssetDatabase.LoadAssetAtPath<GameObject>(gltfPath);
            if (prefab == null)
            {
                Add(sex + " glTF import", "FAIL", "glTFast did not produce a root GameObject prefab for " + gltfPath);
                return;
            }

            Add(sex + " glTF import", "PASS", "glTFast ScriptedImporter produced a native Unity prefab.");

            GameObject instance = null;
            try
            {
                instance = PrefabUtility.InstantiatePrefab(prefab) as GameObject;
                if (instance == null)
                {
                    Add(sex + " prefab instantiation", "FAIL", "PrefabUtility.InstantiatePrefab returned null");
                    return;
                }

                var renderers = instance.GetComponentsInChildren<Renderer>(true);
                var skinned = instance.GetComponentsInChildren<SkinnedMeshRenderer>(true);
                Add(sex + " body parts / renderers", renderers.Length >= 3 ? "PASS" : "FAIL",
                    "renderers=" + renderers.Length + ", skinnedMeshRenderers=" + skinned.Length);

                var materialProblems = ValidateMaterials(instance);
                Add(sex + " materials / shaders / textures", materialProblems.Count == 0 ? "PASS" : "FAIL",
                    materialProblems.Count == 0 ? "no error shader or missing texture property found" : string.Join("; ", materialProblems));

                var uvProblems = ValidateUvAndBones(instance, skinned);
                Add(sex + " UVs / skin bones", uvProblems.Count == 0 ? "PASS" : "FAIL",
                    uvProblems.Count == 0 ? "UV and skin-bone checks passed" : string.Join("; ", uvProblems));

                var bounds = CalculateBounds(renderers);
                var boundsOk = bounds.size.y >= 1.35f && bounds.size.y <= 2.25f &&
                               bounds.min.y >= -0.12f && bounds.min.y <= 0.25f;
                Add(sex + " transform bounds", boundsOk ? "PASS" : "FAIL",
                    "size=" + bounds.size.ToString("F3") + ", minY=" + bounds.min.y.ToString("F3") +
                    "; expected upright ~1.35–2.25 m character standing near y=0");

                var avatarResult = ValidateHumanoidAvatar(instance);
                Add(sex + " Humanoid Avatar", avatarResult.status, avatarResult.detail);

                var retargetResult = ValidateRetargeting(instance, avatarResult.avatar);
                Add(sex + " existing animation FBX retargeting", retargetResult.status, retargetResult.detail);
            }
            catch (Exception exception)
            {
                Add(sex + " Editor validation", "FAIL", exception.ToString());
            }
            finally
            {
                if (instance != null)
                {
                    UnityEngine.Object.DestroyImmediate(instance);
                }
            }
        }

        private static List<string> ValidateMaterials(GameObject instance)
        {
            var problems = new List<string>();
            var renderers = instance.GetComponentsInChildren<Renderer>(true);
            for (var r = 0; r < renderers.Length; r++)
            {
                var materials = renderers[r].sharedMaterials;
                if (materials == null || materials.Length == 0)
                {
                    problems.Add(renderers[r].name + ": no material");
                    continue;
                }

                for (var m = 0; m < materials.Length; m++)
                {
                    var material = materials[m];
                    if (material == null)
                    {
                        problems.Add(renderers[r].name + ": null material");
                        continue;
                    }

                    var shader = material.shader;
                    if (shader == null || shader.name.IndexOf("Error", StringComparison.OrdinalIgnoreCase) >= 0 ||
                        shader.name.IndexOf("InternalError", StringComparison.OrdinalIgnoreCase) >= 0)
                    {
                        problems.Add(material.name + ": missing/error shader");
                        continue;
                    }

                    var textureSlots = 0;
                    var missingTextures = 0;
                    for (var p = 0; p < shader.GetPropertyCount(); p++)
                    {
                        if (shader.GetPropertyType(p) != UnityEngine.Rendering.ShaderPropertyType.Texture)
                        {
                            continue;
                        }

                        var property = shader.GetPropertyName(p);
                        var texture = material.GetTexture(property);
                        if (texture != null)
                        {
                            textureSlots++;
                            if (texture.width <= 0 || texture.height <= 0)
                            {
                                missingTextures++;
                            }
                        }
                    }

                    if (missingTextures > 0)
                    {
                        problems.Add(material.name + ": " + missingTextures + " invalid texture(s)");
                    }
                }
            }

            return problems;
        }

        private static List<string> ValidateUvAndBones(GameObject instance, SkinnedMeshRenderer[] skinned)
        {
            var problems = new List<string>();
            var allBones = new HashSet<string>();
            for (var s = 0; s < skinned.Length; s++)
            {
                var renderer = skinned[s];
                var mesh = renderer.sharedMesh;
                if (mesh == null)
                {
                    problems.Add(renderer.name + ": no shared mesh");
                    continue;
                }

                if (mesh.uv == null || mesh.uv.Length != mesh.vertexCount)
                {
                    problems.Add(renderer.name + ": UV count " + (mesh.uv == null ? 0 : mesh.uv.Length) +
                                 " != vertex count " + mesh.vertexCount);
                }

                if (renderer.bones == null || renderer.bones.Length == 0)
                {
                    problems.Add(renderer.name + ": no skin bones");
                    continue;
                }

                for (var b = 0; b < renderer.bones.Length; b++)
                {
                    if (renderer.bones[b] == null)
                    {
                        problems.Add(renderer.name + ": null bone at " + b);
                    }
                    else
                    {
                        allBones.Add(renderer.bones[b].name);
                    }
                }
            }

            if (allBones.Count < 60)
            {
                problems.Add("only " + allBones.Count + " distinct skin bones found; expected 65-joint source rig");
            }

            return problems;
        }

        private static Bounds CalculateBounds(Renderer[] renderers)
        {
            var bounds = new Bounds(Vector3.zero, Vector3.zero);
            var has = false;
            for (var i = 0; i < renderers.Length; i++)
            {
                if (!has)
                {
                    bounds = renderers[i].bounds;
                    has = true;
                }
                else
                {
                    bounds.Encapsulate(renderers[i].bounds);
                }
            }

            return bounds;
        }

        private struct AvatarResult
        {
            public string status;
            public string detail;
            public Avatar avatar;
        }

        private static AvatarResult ValidateHumanoidAvatar(GameObject instance)
        {
            try
            {
                var rigType = typeof(RigDetectionUtility);
                var aliasesMethod = rigType.GetMethod("BoneAliases", BindingFlags.Static | BindingFlags.NonPublic);
                var normalizeMethod = rigType.GetMethod("NormalizeBoneName", BindingFlags.Static | BindingFlags.NonPublic);
                if (aliasesMethod == null || normalizeMethod == null)
                {
                    return new AvatarResult
                    {
                        status = "NOT VERIFIED",
                        detail = "RigDetectionUtility alias reflection API changed",
                        avatar = null,
                    };
                }

                var transforms = new List<Transform>();
                CollectBreadthFirst(instance.transform, transforms);
                var byNormalized = new Dictionary<string, Transform>(StringComparer.Ordinal);
                for (var i = 0; i < transforms.Count; i++)
                {
                    var normalized = (string)normalizeMethod.Invoke(null, new object[] { transforms[i].name });
                    if (!string.IsNullOrEmpty(normalized) && !byNormalized.ContainsKey(normalized))
                    {
                        byNormalized.Add(normalized, transforms[i]);
                    }
                }

                var parentNameField = typeof(SkeletonBone).GetField(
                    "parentName", BindingFlags.Instance | BindingFlags.NonPublic);
                var skeleton = new SkeletonBone[transforms.Count];
                for (var i = 0; i < transforms.Count; i++)
                {
                    skeleton[i] = new SkeletonBone
                    {
                        name = transforms[i].name,
                        position = transforms[i].localPosition,
                        rotation = transforms[i].localRotation,
                        scale = transforms[i].localScale,
                    };

                    // parentName is internal in Unity's SkeletonBone struct but
                    // is required for AvatarBuilder to reconstruct hierarchy.
                    if (parentNameField != null)
                    {
                        object boxed = skeleton[i];
                        parentNameField.SetValue(boxed,
                            transforms[i].parent == null ? string.Empty : transforms[i].parent.name);
                        skeleton[i] = (SkeletonBone)boxed;
                    }
                }

                var human = new List<HumanBone>();
                var mappedBoneNames = new HashSet<string>();
                var values = (HumanBodyBones[])Enum.GetValues(typeof(HumanBodyBones));
                for (var i = 0; i < values.Length; i++)
                {
                    var bone = values[i];
                    if (bone == HumanBodyBones.LastBone)
                    {
                        continue;
                    }

                    var humanName = (int)bone < HumanTrait.BoneName.Length
                        ? HumanTrait.BoneName[(int)bone]
                        : bone.ToString();
                    var aliases = (string[])aliasesMethod.Invoke(null, new object[] { bone });
                    for (var a = 0; a < aliases.Length; a++)
                    {
                        var normalizedAlias = (string)normalizeMethod.Invoke(null, new object[] { aliases[a] });
                        Transform hit;
                        if (string.IsNullOrEmpty(normalizedAlias) ||
                            !byNormalized.TryGetValue(normalizedAlias, out hit) ||
                            mappedBoneNames.Contains(hit.name))
                        {
                            continue;
                        }

                        human.Add(new HumanBone
                        {
                            boneName = hit.name,
                            humanName = humanName,
                            limit = new HumanLimit { useDefaultValues = true },
                        });
                        mappedBoneNames.Add(hit.name);
                        break;
                    }
                }

                var description = new HumanDescription
                {
                    skeleton = skeleton,
                    human = human.ToArray(),
                    armStretch = 0.05f,
                    legStretch = 0.05f,
                    upperArmTwist = 0.5f,
                    lowerArmTwist = 0.5f,
                    upperLegTwist = 0.5f,
                    lowerLegTwist = 0.5f,
                    feetSpacing = 0f,
                    hasTranslationDoF = false,
                    rootMotionBoneName = string.Empty,
                };

                // AvatarBuilder also reads internal hierarchy flags. Set them
                // explicitly so a runtime-instantiated glTF hierarchy is not
                // mistaken for a parentless skeleton.
                object boxedDescription = description;
                SetPrivateField(boxedDescription, "m_SkeletonHasParents", true);
                SetPrivateField(boxedDescription, "m_HasExtraRoot", false);
                SetPrivateField(boxedDescription, "m_GlobalScale", 1f);
                description = (HumanDescription)boxedDescription;

                var avatar = AvatarBuilder.BuildHumanAvatar(instance, description);
                if (avatar == null || !avatar.isValid || !avatar.isHuman)
                {
                    return new AvatarResult
                    {
                        status = "NOT VERIFIED",
                        detail = "AvatarBuilder produced " + (avatar == null ? "null" :
                            "isValid=" + avatar.isValid + ", isHuman=" + avatar.isHuman) +
                            "; mappedHumanBones=" + human.Count +
                            ". glTFast runtime hierarchy was not accepted as a Humanoid Avatar; use Generic or a dedicated Humanoid conversion. No rig was forced.",
                        avatar = null,
                    };
                }

                return new AvatarResult
                {
                    status = "PASS",
                    detail = "Avatar.isValid && Avatar.isHuman; " + human.Count + " human bones mapped from " +
                             transforms.Count + " transforms",
                    avatar = avatar,
                };
            }
            catch (Exception exception)
            {
                return new AvatarResult
                {
                    status = "NOT VERIFIED",
                    detail = "AvatarBuilder check could not be completed: " + exception.Message,
                    avatar = null,
                };
            }
        }

        private struct RetargetResult
        {
            public string status;
            public string detail;
        }

        private static RetargetResult ValidateRetargeting(GameObject instance, Avatar avatar)
        {
            if (avatar == null)
            {
                return new RetargetResult
                {
                    status = "NOT VERIFIED",
                    detail = "no valid test Avatar was produced, so retargeting was not sampled",
                };
            }

            AnimationClip clip = null;
            var assets = AssetDatabase.LoadAllAssetsAtPath(ExistingClipPath);
            for (var i = 0; i < assets.Length; i++)
            {
                var candidate = assets[i] as AnimationClip;
                if (candidate != null && candidate.humanMotion)
                {
                    clip = candidate;
                    break;
                }
            }

            if (clip == null)
            {
                return new RetargetResult
                {
                    status = "NOT VERIFIED",
                    detail = "no Humanoid AnimationClip found in " + ExistingClipPath,
                };
            }

            var animator = instance.GetComponent<Animator>();
            if (animator == null)
            {
                animator = instance.AddComponent<Animator>();
            }

            animator.avatar = avatar;
            animator.runtimeAnimatorController = null;
            animator.applyRootMotion = false;

            Transform spine = null;
            var allTransforms = instance.GetComponentsInChildren<Transform>(true);
            for (var i = 0; i < allTransforms.Length; i++)
            {
                var name = allTransforms[i].name.ToLowerInvariant();
                if (name.Contains("spine_01") || name.Contains("spine1") || name.Contains("spine"))
                {
                    spine = allTransforms[i];
                    break;
                }
            }

            if (spine == null)
            {
                return new RetargetResult
                {
                    status = "NOT VERIFIED",
                    detail = "no spine transform found to measure retargeted motion",
                };
            }

            var before = spine.localRotation;
            var started = false;
            try
            {
                AnimationMode.StartAnimationMode();
                started = true;
                AnimationMode.BeginSampling();
                AnimationMode.SampleAnimationClip(instance, clip, 0.5f);
                AnimationMode.EndSampling();
            }
            catch (Exception exception)
            {
                return new RetargetResult
                {
                    status = "NOT VERIFIED",
                    detail = "AnimationMode sampling is unavailable in this batch-mode context: " + exception.Message,
                };
            }
            finally
            {
                if (started)
                {
                    AnimationMode.StopAnimationMode();
                }
            }

            var after = spine.localRotation;
            var angle = Quaternion.Angle(before, after);
            return new RetargetResult
            {
                status = angle > 0.01f ? "PASS" : "NOT VERIFIED",
                detail = angle > 0.01f
                    ? "existing Humanoid clip sampled through the test Avatar; spine rotation changed by " +
                      angle.ToString("F3") + " degrees"
                    : "clip sampled but spine rotation did not change; retargeting result needs manual visual confirmation",
            };
        }

        private static void SetPrivateField(object boxedStruct, string fieldName, object value)
        {
            var field = typeof(HumanDescription).GetField(
                fieldName, BindingFlags.Instance | BindingFlags.NonPublic);
            if (field != null)
            {
                field.SetValue(boxedStruct, value);
            }
        }

        private static void CollectBreadthFirst(Transform root, List<Transform> output)
        {
            var queue = new Queue<Transform>();
            queue.Enqueue(root);
            while (queue.Count > 0)
            {
                var current = queue.Dequeue();
                output.Add(current);
                for (var i = 0; i < current.childCount; i++)
                {
                    queue.Enqueue(current.GetChild(i));
                }
            }
        }

        private static void Add(string check, string status, string detail)
        {
            Rows.Add(new Row { check = check, status = status, detail = detail });
        }

        private static string Escape(string text)
        {
            return string.IsNullOrEmpty(text)
                ? string.Empty
                : text.Replace("|", "\\|").Replace("\r", " ").Replace("\n", " ");
        }
