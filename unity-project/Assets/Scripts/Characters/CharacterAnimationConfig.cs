    /// <summary>The animation categories the Character/Animation Managers assign into.</summary>
    public enum CharacterAnimCategory
    {
        Idle,
        Walk,
        Run,
        Sprint,
        Jump,
        Fall,
        Crouch,
        CrouchWalk,
        Aim,
        RifleRun,
        RifleIdle,
        Shoot,
        Reload,
        WeaponSwitch,
        Melee,
        Death,
    }

