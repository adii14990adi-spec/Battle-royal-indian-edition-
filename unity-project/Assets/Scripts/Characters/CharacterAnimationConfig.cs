        };
    }

    /// <summary>One category → clip assignment for one character.</summary>
    [Serializable]
    public sealed class CharacterAnimAssignment
    {
        /// <summary>Null, empty or whitespace = shared default; otherwise this character's override.</summary>
        public string characterId;
        public CharacterAnimCategory category;
        public AnimationClip clip;
        public string sourcePath;
        public float duration;
        public float frameRate;
        public bool loop;
        public bool retargetable;
    }

    /// <summary>An imported (or custom) base character and everything derived from it.</summary>
    [Serializable]
    public sealed class CharacterDefinition
    {
        public string id;
        public string displayName;
        public GameObject model;
        public RuntimeAnimatorController controller;
        public bool humanoidRigValid;
        public string rigReport;
        public string materialReport;
        // Assignments live on the config (shared defaults + per-character
        // overrides keyed by CharacterAnimAssignment.characterId) so different
        // characters can use different clips from the same imported library.
    }

    /// <summary>Provenance record used to prevent duplicate imports.</summary>
    [Serializable]
    public sealed class ImportedSourceRecord
    {
        public string sourcePath;
        public string sha256;
        public long bytes;
        public string importedAtUtc;
    }

    /// <summary>
    /// Saved character ↔ animation configuration, written by the editor-time
    /// Character &amp; Animation Manager and read by the runtime preview,
    /// the player visual, and the in-game Character Bay.
    /// Lives under <c>Assets/Generated/Resources/</c> so builds can load it
    /// without hard-coded GUID references. It is code-generated by
    /// <c>CharacterAnimationIntegration.BuildFromCommandLine</c>; the FBX
    /// assets themselves keep the stable committed GUIDs from PR #25 and the
    /// two character .fbx.meta files.
    /// </summary>
    public sealed class CharacterAnimationConfig : ScriptableObject
    {
        /// <summary>Resources.Load path (file lives in any Resources folder).</summary>
        public const string ResourcePath = "CharacterAnimationConfig";

        /// <summary>
        /// Unity deserializes a null serialized string as an empty string. A
        /// shared assignment can therefore be null, empty or whitespace after a
        /// domain reload. Whitespace-only IDs are treated as shared too, so an
        /// accidental inspector value can never masquerade as a character ID.
        /// </summary>
        public static bool IsSharedCharacterId(string id)
        {
            return string.IsNullOrEmpty(id) || string.IsNullOrEmpty(id.Trim());
        }

        /// <summary>Trimmed ID used for case-insensitive per-character lookups.</summary>
        public static string NormalizeCharacterId(string id)
        {
            return string.IsNullOrEmpty(id) ? string.Empty : id.Trim();
        }

        public List<CharacterDefinition> characters = new List<CharacterDefinition>();
        public List<ImportedSourceRecord> importedSources = new List<ImportedSourceRecord>();
        /// <summary>All imported animation clips (deduplicated by reference).</summary>
        public List<AnimationClip> clips = new List<AnimationClip>();
        /// <summary>
        /// Category assignments: characterId null = shared default, otherwise
        /// a per-character override. One entry per (characterId, category).
        /// </summary>
        public List<CharacterAnimAssignment> assignments = new List<CharacterAnimAssignment>();
        public string selectedCharacterId = "male";
        public string generatedAtUtc;

        public static CharacterAnimationConfig Load()
        {
            return Resources.Load<CharacterAnimationConfig>(ResourcePath);
        }

        public CharacterDefinition FindCharacter(string id)
        {
            if (characters == null || string.IsNullOrEmpty(id))
            {
                return null;
            }

            for (var i = 0; i < characters.Count; i++)
            {
                if (characters[i] != null && string.Equals(characters[i].id, id, StringComparison.OrdinalIgnoreCase))
                {
                    return characters[i];
                }
            }

            return null;
        }

        public CharacterDefinition SelectedCharacter()
        {
            var found = FindCharacter(selectedCharacterId);
            if (found != null)
            {
                return found;
            }

            if (characters != null && characters.Count > 0)
            {
                for (var i = 0; i < characters.Count; i++)
                {
                    if (characters[i] != null && characters[i].model != null)
                    {
                        return characters[i];
                    }
                }
            }

            return null;
        }

        /// <summary>
        /// The assignment for a category: a case-insensitive character override
        /// when present, otherwise the null/empty/whitespace shared default.
        /// Unmatched or null character IDs deliberately fall back to the shared
        /// assignment; Male and Female overrides stay independent.
        /// </summary>
        public CharacterAnimAssignment FindAssignment(string characterId, CharacterAnimCategory category)
        {
            if (assignments == null)
            {
                return null;
            }

            var requested = NormalizeCharacterId(characterId);
            var hasRequested = !string.IsNullOrEmpty(requested);
            CharacterAnimAssignment fallback = null;
            for (var i = 0; i < assignments.Count; i++)
            {
                var assignment = assignments[i];
                if (assignment == null || assignment.category != category)
                {
                    continue;
                }

                var shared = IsSharedCharacterId(assignment.characterId);
                if (shared)
                {
                    if (fallback == null)
                    {
                        fallback = assignment;
                    }
                    continue;
                }

                if (hasRequested && string.Equals(
                        NormalizeCharacterId(assignment.characterId), requested,
                        StringComparison.OrdinalIgnoreCase))
                {
                    return assignment;
                }
            }

            return fallback;
        }

        public AnimationClip FindClip(string characterId, CharacterAnimCategory category)
        {
            var assignment = FindAssignment(characterId, category);
            return assignment != null ? assignment.clip : null;
        }

        /// <summary>Register an imported clip once (reference dedupe).</summary>
        public void AddClip(AnimationClip clip)
        {
            if (clip == null)
            {
                return;
            }

            if (clips == null)
            {
                clips = new List<AnimationClip>();
            }

            if (!clips.Contains(clip))
            {
                clips.Add(clip);
            }
        }

        /// <summary>
        /// Insert or replace the assignment for (characterId, category).
        /// Returns true when an existing entry was replaced.
        /// </summary>
        public bool AddOrUpdateAssignment(CharacterAnimAssignment assignment, string characterId)
        {
            if (assignment == null)
            {
                return false;
            }

            if (assignments == null)
            {
                assignments = new List<CharacterAnimAssignment>();
            }

            assignment.characterId = characterId;
            for (var i = 0; i < assignments.Count; i++)
            {
                var existing = assignments[i];
                if (existing != null
                    && existing.category == assignment.category
                    && string.Equals(existing.characterId ?? string.Empty,
                        assignment.characterId ?? string.Empty,
                        StringComparison.OrdinalIgnoreCase))
                {
                    assignments[i] = assignment;
                    return true;
                }
            }

            assignments.Add(assignment);
            return false;
        }

        /// <summary>True when this exact file content was imported before.</summary>
        public bool IsDuplicateSource(string sha256)
        {
            if (importedSources == null || string.IsNullOrEmpty(sha256))
            {
                return false;
            }

            for (var i = 0; i < importedSources.Count; i++)
            {
                var record = importedSources[i];
                if (record != null && string.Equals(record.sha256, sha256, StringComparison.OrdinalIgnoreCase))
                {
                    return true;
                }
            }

            return false;
        }

        public void AddOrUpdateSource(ImportedSourceRecord record)
        {
            if (record == null || string.IsNullOrEmpty(record.sha256))
            {
                return;
            }

            if (importedSources == null)
            {
                importedSources = new List<ImportedSourceRecord>();
            }

            for (var i = 0; i < importedSources.Count; i++)
            {
                var existing = importedSources[i];
                if (existing != null && string.Equals(existing.sha256, record.sha256, StringComparison.OrdinalIgnoreCase))
                {
                    importedSources[i] = record;
                    return;
                }
            }

            importedSources.Add(record);
        }

        /// <summary>
        /// Counts dangling references (removed assets) so the preview and the
        /// player visual can fall back honestly instead of showing nothing.
        /// </summary>
        public string ValidateReferences(out int missing)
        {
            missing = 0;
            if (characters == null || characters.Count == 0)
            {
                return "no characters imported yet";
            }

            var lines = new List<string>();
            for (var i = 0; i < characters.Count; i++)
            {
                var character = characters[i];
                if (character == null)
                {
                    missing++;
                    continue;
                }

                if (character.model == null)
                {
                    missing++;
                    lines.Add(character.displayName + ": model reference missing");
                }

                if (character.controller == null)
                {
                    missing++;
                    lines.Add(character.displayName + ": animator controller missing (save assignments to regenerate)");
                }
            }

            if (assignments != null)
            {
                for (var a = 0; a < assignments.Count; a++)
                {
                    var assignment = assignments[a];
                    if (assignment != null && assignment.clip == null)
                    {
                        missing++;
                        lines.Add((string.IsNullOrEmpty(assignment.characterId)
                            ? "default"
                            : assignment.characterId) + ": " + assignment.category + " clip missing");
                    }
                }
            }

            return missing == 0
                ? "all references valid (" + characters.Count + " characters)"
                : string.Join("\n", lines);
        }
    }

    /// <summary>
    /// Category metadata: folder routing (§ asset organization), display names,
    /// loop defaults and filename → category inference used by the
    /// Animation Manager for both new uploads and the already-uploaded pack.
    /// </summary>
    public static class CharacterAnimCategories
    {
        public static readonly CharacterAnimCategory[] All =
        {
            CharacterAnimCategory.Idle,
            CharacterAnimCategory.Walk,
            CharacterAnimCategory.Run,
            CharacterAnimCategory.Sprint,
            CharacterAnimCategory.Jump,
            CharacterAnimCategory.Fall,
            CharacterAnimCategory.Crouch,
            CharacterAnimCategory.CrouchWalk,
            CharacterAnimCategory.Aim,
            CharacterAnimCategory.RifleRun,
            CharacterAnimCategory.RifleIdle,
            CharacterAnimCategory.Shoot,
            CharacterAnimCategory.Reload,
            CharacterAnimCategory.WeaponSwitch,
            CharacterAnimCategory.Melee,
            CharacterAnimCategory.Death,
        };

        public static string DisplayName(CharacterAnimCategory category)
        {
            switch (category)
            {
                case CharacterAnimCategory.CrouchWalk: return "Crouch Walk";
                case CharacterAnimCategory.RifleRun: return "Rifle Run";
                case CharacterAnimCategory.RifleIdle: return "Rifle Idle";
                case CharacterAnimCategory.WeaponSwitch: return "Weapon Switching";
                default: return category.ToString();
            }
        }

        /// <summary>Sub-folder of Assets/Animations this category is filed under.</summary>
        public static string FolderName(CharacterAnimCategory category)
        {
            switch (category)
            {
                case CharacterAnimCategory.Idle:
                case CharacterAnimCategory.Walk:
                case CharacterAnimCategory.Run:
                case CharacterAnimCategory.Sprint:
                case CharacterAnimCategory.Jump:
                case CharacterAnimCategory.Fall:
                case CharacterAnimCategory.RifleRun:
                    return "Movement";
                case CharacterAnimCategory.Crouch:
                case CharacterAnimCategory.CrouchWalk:
                    return "Crouch";
                case CharacterAnimCategory.Aim:
                case CharacterAnimCategory.Melee:
                    return "Combat";
                case CharacterAnimCategory.RifleIdle:
                case CharacterAnimCategory.Shoot:
                case CharacterAnimCategory.Reload:
                case CharacterAnimCategory.WeaponSwitch:
                    return "Weapon";
                case CharacterAnimCategory.Death:
                    return "Death";
                default:
                    return "Movement";
            }
        }

        /// <summary>Cycles and idle poses loop by default; one-shots do not.</summary>
        public static bool DefaultLoop(CharacterAnimCategory category)
        {
            switch (category)
            {
                case CharacterAnimCategory.Idle:
                case CharacterAnimCategory.Walk:
                case CharacterAnimCategory.Run:
                case CharacterAnimCategory.Sprint:
                case CharacterAnimCategory.Crouch:
                case CharacterAnimCategory.CrouchWalk:
                case CharacterAnimCategory.Aim:
                case CharacterAnimCategory.RifleRun:
                case CharacterAnimCategory.RifleIdle:
                    return true;
                default:
                    return false;
            }
        }

        /// <summary>
        /// Filename → category heuristic (examples, not mandatory names).
        /// Rules are ordered: first match wins. Unknown names fall back to
        /// Movement and the import report asks the user to review them.
        /// </summary>
        public static CharacterAnimCategory InferFromFileName(string fileName)
        {
            var name = (fileName ?? string.Empty).ToLowerInvariant();

            if (name.Contains("death") || name.Contains("dying") || name.Contains("die "))
            {
                return CharacterAnimCategory.Death;
            }

            if (name.Contains("reload"))
            {
                return CharacterAnimCategory.Reload;
            }

            if (name.Contains("firing") || name.Contains("shoot") || name.Contains("shooting"))
            {
                return CharacterAnimCategory.Shoot;
            }

            if (name.Contains("rifle aiming") || (name.Contains("rifle") && name.Contains("idle") && name.Contains("aim")))
            {
                return CharacterAnimCategory.RifleIdle;
            }

            if (name.Contains("aiming idle") || name.Contains("rifle aiming idle"))
            {
                return CharacterAnimCategory.RifleIdle;
            }

            if (name.Contains("rifle run") || name.Contains("rifle sprint") || name.Contains("run with rifle"))
            {
                return CharacterAnimCategory.RifleRun;
            }

            if (name.Contains("aim"))
            {
                return CharacterAnimCategory.Aim;
            }

            if (name.Contains("switch") || name.Contains("holster") || name.Contains("grab and put")
                || name.Contains("equip") || name.Contains("draw weapon"))
            {
                return CharacterAnimCategory.WeaponSwitch;
            }

            if ((name.Contains("walk") && name.Contains("crouch"))
                || (name.Contains("crouch") && name.Contains("walk"))
                || name.Contains("crouching walk"))
            {
                return CharacterAnimCategory.CrouchWalk;
            }

            if (name.Contains("crouch") || name.Contains("prone"))
            {
                return CharacterAnimCategory.Crouch;
            }

            if (name.Contains("sprint"))
            {
                return CharacterAnimCategory.Sprint;
            }

            if (name.Contains("run") || name.Contains("jog"))
            {
                return CharacterAnimCategory.Run;
            }

            if (name.Contains("walk") || name.Contains("strafe"))
            {
                return CharacterAnimCategory.Walk;
            }

            if (name.Contains("jump down") || name.Contains("fall") || name.Contains("land"))
            {
                return CharacterAnimCategory.Fall;
            }

            if (name.Contains("jump"))
            {
                return CharacterAnimCategory.Jump;
            }

            if (name.Contains("grenade") || name.Contains("melee") || name.Contains("punch")
                || name.Contains("kick") || name.Contains("hit reaction") || name.Contains("tackle")
                || name.Contains("dive") || name.Contains("roll") || name.Contains("dodge"))
            {
                return CharacterAnimCategory.Melee;
            }

            if (name.Contains("turn"))
            {
                return CharacterAnimCategory.Walk;
            }

            if (name.Contains("idle") || name.Contains("stand"))
            {
                return CharacterAnimCategory.Idle;
            }

            return CharacterAnimCategory.Walk;
        }
    }
}
